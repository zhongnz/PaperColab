import assert from 'node:assert/strict';
import { createRequire } from 'node:module';
import { resolve, join } from 'node:path';
import { pathToFileURL } from 'node:url';
import { readFile, writeFile } from 'node:fs/promises';
import { cellSession } from './cells.mjs';

const upstream = resolve(process.argv[2]);
const require = createRequire(import.meta.url);
const { LoroDoc, LoroText } = await import(pathToFileURL(join(upstream,'web/papercolab-loro.mjs')));
const load = name => import(pathToFileURL(join(upstream, 'web/src/lib', name + '.js')));
const {cursorAt} = await load('loro-cursor');
const anchors = await load('anchors'), tracking = await load('track-changes');
require('../../web/vendor/latex.min.js');
require('../../web/blocks.js');
globalThis.zip = require('../../web/vendor/zip-core.min.js');
require('../../web/archive.js');
const archive = new Blob([await readFile(process.argv[3])]);
const filename = 'estuary/sections/methods.tex';
const files = await PaperColabArchive.readArchive(archive);
const original = files.get(filename).text;
const doc = new LoroDoc(), fileId = crypto.randomUUID();
doc.getMap('files').setContainer(fileId, new LoroText()).insert(0, original);
doc.getMap('paths').set(fileId,filename);
doc.commit();
const make = (d, author) => cellSession({doc:d, fileId, model:PaperColabBlocks, anchors, cursorAt, tracking, actor:{who:author,author}});
const alice = make(doc,'Alice');
const paragraph = alice.parse().blocks.find(b=>b.kind==='paragraph');
const heading = alice.parse().blocks.find(b=>b.kind==='heading');
const cell = alice.attach(paragraph), title = alice.attach(heading);
function peer() {
  const d = new LoroDoc();
  d.import(doc.export({mode:'snapshot'}));
  return d;
}
const replica = peer(), bob = make(replica,'Bob');
function sync(d) {
  doc.import(d.export({mode:'update',from:doc.oplogVersion()}));
  d.import(doc.export({mode:'update',from:d.oplogVersion()}));
}
const boundaryPeer = make(peer(),'Dana');
const edge = boundaryPeer.read(cell);
boundaryPeer.markup(edge, 'Prefix '+edge.source+' End.');
assert.equal(boundaryPeer.read(cell)?.source,'Prefix '+edge.source+' End.');
const before = alice.read(cell), rich = structuredClone(before.block.rich);
rich.content[0].content[0].text = rich.content[0].content[0].text.replace('fictional','coastal');
const ids = alice.visual(before,rich);
assert.ok(ids.length);
const idx = bob.body().indexOf('Sampling');
bob.source([{from:idx,to:idx+8,insert:'Station'}]);
sync(replica);
assert.equal(bob.body(),alice.body());
assert.match(alice.read(title).source,/Station method/);
assert.match(bob.read(cell).source,/coastal/);
assert.ok(tracking.listChanges(replica).some(c=>c.id===ids[0] && c.author==='Alice'));
assert.throws(()=>alice.visual(before,rich),/Cell changed/);
assert.ok(tracking.accept(replica,ids[0]));
replica.commit();
sync(replica);
assert.equal(tracking.listChanges(doc).length,0);
const pos = bob.body().indexOf('coastal');
bob.source([{from:pos,to:pos+7,insert:'marine'}]);
sync(replica);
assert.match(PaperColabBlocks.preview(alice.read(cell).block.rich),/marine/);
const tail = original.slice(original.indexOf('\\begin{tabular}'));
assert.ok(alice.body().endsWith(tail));
const exported = await PaperColabArchive.exportArchive(archive,new Map([[filename,alice.body()]]));
const restored = await PaperColabArchive.readArchive(exported);
assert.equal(restored.get(filename).text,alice.body());
for(const [path,entry] of files) if(path!==filename) assert.equal(restored.get(path).text,entry.text);
await writeFile(process.argv[4],Buffer.from(await exported.arrayBuffer()));
// Move by a deliberate cut and paste. The upstream move memory carries the anchor.
const moved = bob.read(cell);
bob.source([{from:moved.block.from,to:moved.block.to,insert:''}]);
const end = bob.body().length;
bob.source([{from:end,to:end,insert:'\n\n'+moved.source+'\n'}]);
sync(replica);
assert.equal(alice.read(cell)?.source,moved.source);
const fresh = make(peer(),'Caroline');
assert.equal(fresh.read(cell)?.source,moved.source);
const split = alice.body().lastIndexOf('pairs');
alice.source([{from:split,to:split,insert:'\n\n'}]);
sync(replica);
assert.equal(bob.read(cell),null);
assert.equal(make(peer(),'Return').read(cell),null);
console.log('PASS: adjacent disconnected edits, both editing directions, tracked acceptance, stale draft, export, cell move, snapshot reconnect, unresolved split.');
