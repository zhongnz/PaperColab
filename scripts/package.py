"""Package the example ZIP and the offline, single-file browser tool."""
import argparse
import base64
import hashlib
import io
from pathlib import Path
import re
import zipfile

REPO = Path(__file__).resolve().parents[1]
WEB = REPO / "web"


def demo_zip():
    buffer = io.BytesIO()
    example = REPO / "examples" / "estuary"
    with zipfile.ZipFile(buffer, "w") as archive:
        for path in sorted(example.rglob("*")):
            if path.is_file():
                item = zipfile.ZipInfo(path.relative_to(example.parent).as_posix())
                item.create_system = 3
                item.external_attr = 0o100644 << 16
                archive.writestr(item, path.read_bytes())
    return buffer.getvalue()


def single_html():
    source = (WEB / "index.html").read_text(encoding="utf-8")
    script_hashes = []

    def inline(match):
        tag = "script" if match[1] else "style"
        path = match[1] or match[2]
        content = (WEB / path).read_text(encoding="utf-8")
        if tag == "script":
            content = content.replace("</script", r"<\/script")
            digest = base64.b64encode(hashlib.sha256(content.encode()).digest()).decode()
            script_hashes.append("'sha256-" + digest + "'")
        return "<" + tag + ">" + content + "</" + tag + ">"

    source = re.sub(r'<script src="([^"]+)"></script>|<link rel="stylesheet" href="([^"]+)">', inline, source)
    source = source.replace("script-src 'self'", "script-src " + " ".join(script_hashes))
    notices = (REPO / "LICENSE").read_text(encoding="utf-8") + "\nzip.js\n" + (WEB / "vendor/zip-LICENSE.txt").read_text(encoding="utf-8")
    notices += "\n" + (WEB / "vendor/editor-NOTICES.txt").read_text(encoding="utf-8")
    return source.replace("</html>", "<!-- Distribution licences\n" + notices.replace("--", "- -") + "\n-->\n</html>")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--html", type=Path, help="write a single offline HTML file")
    parser.add_argument("--zip", type=Path, help="write the example project ZIP")
    parser.add_argument("--refresh-example", action="store_true", help="update the copy embedded in the browser tool")
    args = parser.parse_args()
    data = demo_zip()
    script = "// Generated by scripts/package.py from examples/estuary.\n"
    script += "globalThis.PaperColabExample = '" + base64.b64encode(data).decode() + "';\n"
    target = WEB / "example.js"
    if args.refresh_example:
        target.write_text(script, encoding="utf-8")
    elif target.read_text(encoding="utf-8") != script:
        raise SystemExit("The embedded example is stale. Run with --refresh-example.")
    if args.zip:
        args.zip.write_bytes(data)
    if args.html:
        args.html.write_text(single_html(), encoding="utf-8")
